PROMPT == Pre-check: the three roles must exist, and this must be the intended schema
SELECT SYS_CONTEXT('USERENV','SESSION_USER') AS connected_as,
       SYS_CONTEXT('USERENV','CON_NAME')     AS container
  FROM dual;

DECLARE
  v_roles NUMBER;
  v_users NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_roles FROM roles
   WHERE role_name IN ('ADMIN','MANAGER','MEMBER');
  IF v_roles <> 3 THEN
    RAISE_APPLICATION_ERROR(-20001,
      'ROLES must contain ADMIN, MANAGER and MEMBER before this migration (found ' || v_roles || ').');
  END IF;
  SELECT COUNT(*) INTO v_users FROM users;
  DBMS_OUTPUT.PUT_LINE('Pre-check OK: 3 roles present, ' || v_users || ' users (left untouched).');
END;
