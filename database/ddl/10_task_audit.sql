-- Soft delete / Recycle Bin audit log (migration 005). Append-only: the application only INSERTs.
-- Keep identical to the CREATE statements in migrations/005_task_soft_delete.sql.
--
-- task_id and project_id deliberately have NO foreign key: the history must survive even if a
-- project (and with it its tasks) is later removed. A project that still holds soft-deleted
-- tasks cannot be deleted at all, so a DELETE entry never loses a recoverable task silently.
-- task_title is a snapshot, so an entry stays readable after the task changes or disappears.

CREATE TABLE task_audit_log (
  audit_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id    NUMBER        NOT NULL,
  project_id NUMBER        NOT NULL,
  task_title VARCHAR2(200) NOT NULL,
  action     VARCHAR2(10)  NOT NULL,
  actor_id   NUMBER        NOT NULL,
  acted_at   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  details    VARCHAR2(1000),
  CONSTRAINT ck_task_audit_action CHECK (action IN ('DELETE','RESTORE')),
  CONSTRAINT fk_task_audit_actor  FOREIGN KEY (actor_id) REFERENCES users (user_id)
);

CREATE INDEX ix_task_audit_task    ON task_audit_log (task_id, acted_at);
CREATE INDEX ix_task_audit_project ON task_audit_log (project_id, acted_at);
CREATE INDEX ix_task_audit_actor   ON task_audit_log (actor_id);
