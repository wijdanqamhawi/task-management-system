-- RBAC Phase 1 - PERMISSIONS and ROLE_PERMISSIONS.
-- Additive: creates two tables and one index. No existing table or row is touched; the existing
-- users.role_id -> roles relationship and the three roles are unchanged.
--
-- A permission is a global capability a role holds (many-to-many). It is NOT a replacement for
-- the resource-level rules (project membership, project manager, assignee, creator/uploader),
-- which depend on the specific row and stay in the application. See seed/rbac_data.sql.
-- Rows are loaded by seed/rbac_data.sql. For an already populated database use
-- ../migrations/001_rbac_permissions.sql instead of this file.

CREATE TABLE permissions (
  permission_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  permission_code VARCHAR2(50)  NOT NULL,
  description     VARCHAR2(200),
  CONSTRAINT uq_permissions_code UNIQUE (permission_code),
  -- Codes are stable identifiers the application compares against: upper case, no spaces.
  CONSTRAINT ck_permissions_code CHECK (REGEXP_LIKE(permission_code, '^[A-Z][A-Z0-9_]*$'))
);

-- Many-to-many between roles and permissions. No ON DELETE CASCADE: roles and permissions are
-- reference data and must not be removable while grants exist.
CREATE TABLE role_permissions (
  role_id       NUMBER NOT NULL,
  permission_id NUMBER NOT NULL,
  granted_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_role_permissions PRIMARY KEY (role_id, permission_id),
  CONSTRAINT fk_rp_role       FOREIGN KEY (role_id)       REFERENCES roles (role_id),
  CONSTRAINT fk_rp_permission FOREIGN KEY (permission_id) REFERENCES permissions (permission_id)
);

-- The primary key already serves "permissions of a role"; this serves "roles holding a
-- permission" and the foreign-key lookup on permission_id.
CREATE INDEX ix_role_permissions_permission ON role_permissions (permission_id);
