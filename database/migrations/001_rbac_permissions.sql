-- Expect 21 permissions; ADMIN 21, MANAGER 17, MEMBER 9 (above). Existing data is unchanged.
SELECT 'roles'             AS table_name, COUNT(*) AS row_count FROM roles
UNION ALL SELECT 'permissions',      COUNT(*) FROM permissions
UNION ALL SELECT 'role_permissions', COUNT(*) FROM role_permissions
UNION ALL SELECT 'users (untouched)', COUNT(*) FROM users;

-- Must return no rows: every constraint and the index exist and are enabled.
SELECT 'MISSING OR DISABLED: ' || w.name AS problem
  FROM (SELECT 'UQ_PERMISSIONS_CODE' AS name FROM dual UNION ALL
        SELECT 'CK_PERMISSIONS_CODE' FROM dual UNION ALL
        SELECT 'PK_ROLE_PERMISSIONS' FROM dual UNION ALL
        SELECT 'FK_RP_ROLE'          FROM dual UNION ALL
        SELECT 'FK_RP_PERMISSION'    FROM dual) w
 WHERE NOT EXISTS (SELECT 1 FROM user_constraints c
                    WHERE c.constraint_name = w.name AND c.status = 'ENABLED')
UNION ALL
SELECT 'MISSING INDEX: IX_ROLE_PERMISSIONS_PERMISSION' FROM dual
 WHERE NOT EXISTS (SELECT 1 FROM user_indexes WHERE index_name = 'IX_ROLE_PERMISSIONS_PERMISSION');

