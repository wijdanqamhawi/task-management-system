-- Migration 001 - database-driven RBAC, Phase 1 (schema + seed only).
--
-- For a database that ALREADY holds real data. Non-destructive and idempotent:
--   * CREATE TABLE / CREATE INDEX only, each guarded so a second run reports "already exists"
--     (ORA-00955) and carries on. Nothing is dropped, truncated, deleted or altered.
--   * USERS, ROLES, PROJECT_MEMBERS and every other existing table are not touched; the three
--     roles and users.role_id are unchanged.
--   * Rows are added with MERGE ... WHEN NOT MATCHED THEN INSERT (seed/rbac_data.sql): existing
--     rows are never updated or removed.
--   * No application behaviour changes: the backend and frontend do not read these tables yet.
--
-- Run as the schema owner (the same account that owns USERS), from this directory:
--   sqlplus <schema_owner>@//<host>:1521/<service> @001_rbac_permissions.sql
-- You are prompted for the password; do not put it on the command line or in this file.
--
-- Prerequisite: ROLES already contains ADMIN, MANAGER and MEMBER (seed/reference_data.sql).
-- The CREATE statements below must stay identical to ddl/09_rbac.sql.
--
-- Oracle DDL commits implicitly, so this cannot be rolled back as a unit. That is safe here
-- because every step is additive and a re-run completes whatever is missing.
SET ECHO ON
