-- T160 - PASSWORD_RESET_TOKENS. Forgot-password flow (research.md R-002).
-- Additive: creates one table and one index. No existing table or row is touched.
--
-- Only the SHA-256 hash of a reset token is stored (CHAR(64) hex); the raw token exists only
-- in the e-mailed link. A token is single use (used_at) and expires 15 minutes after issue.
-- ON DELETE CASCADE removes a user's tokens with the user (users are deactivated, not
-- deleted, in the application; only the ZZTEST test cleanup removes users).

CREATE TABLE password_reset_tokens (
  token_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     NUMBER       NOT NULL,
  token_hash  CHAR(64)     NOT NULL,
  created_at  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  expires_at  TIMESTAMP    NOT NULL,
  used_at     TIMESTAMP,
  request_ip  VARCHAR2(45),
  CONSTRAINT uq_prt_token_hash UNIQUE (token_hash),
  CONSTRAINT fk_prt_user FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE
);

CREATE INDEX ix_prt_user_created ON password_reset_tokens (user_id, created_at);
